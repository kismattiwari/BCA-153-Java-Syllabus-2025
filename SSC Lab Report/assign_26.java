public class assign_26 {
    public static void main(String[] args) {

        // Autoboxing
        int a = 10;
        Integer x = a;

        // Unboxing
        Integer y = 20;
        int b = y;

        System.out.println("Autoboxing: " + x);
        System.out.println("Unboxing: " + b);
    }
}